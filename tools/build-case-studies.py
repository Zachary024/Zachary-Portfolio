def build(project):
    built = "\n".join(f"              <li>{item}</li>" for item in project["built"])
    stack = "\n".join(f"                <li>{tool}</li>" for tool in project["stack"])
    data = {**project, "built": built, "stack": stack}
    html = HEAD.format(**data)
    path = OUT / f"{project['slug']}.html"
    path.write_text(html)
    return path


def write_noscript_fallback(projects):
    """Keep the no-JS fallback in index.html in sync with the data.

    Without JavaScript the cards cannot render, so the work section would be
    empty. This writes a plain list of links to the generated case studies —
    enough for a visitor (or a crawler) to see the work and reach it.
    """
    index = ROOT / "index.html"
    html = index.read_text()
    items = "\n".join(
        f'                <li><a href="work/{p["slug"]}.html">{p["title"]}</a>'
        f' — {p["category"].lower()}, {p["year"]}</li>'
        for p in projects
    )
    block = (
        "              <!-- FALLBACK:START — generated from assets/projects.js by\n"
        "                   tools/build-case-studies.py. Re-run it after editing data. -->\n"
        '              <p class="work-grid__fallback">\n'
        "                JavaScript is off, so the interactive cards are hidden.\n"
        "                The case studies still work:\n"
        "              </p>\n"
        "              <ul class=\"work-grid__fallback\">\n"
        f"{items}\n"
        "              </ul>\n"
        "              <!-- FALLBACK:END -->"
    )
    html = re.sub(
        r"<!-- FALLBACK:START.*?FALLBACK:END -->", lambda m: block, html, flags=re.S
    )
    index.write_text(html)
    print("updated", index.name, "fallback")


def main():
    OUT.mkdir(exist_ok=True)
    projects = load_projects()
    for project in projects:
        print("wrote", build(project).relative_to(ROOT))
    write_noscript_fallback(projects)
    print(f"{len(projects)} case studies.")


if __name__ == "__main__":
    main()
