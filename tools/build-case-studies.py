#!/usr/bin/env python3
"""Generate one case-study page per project in assets/projects.js.

    python3 tools/build-case-studies.py

Reads assets/projects.js (the JSON array between the brackets), writes
work/<slug>.html for each project, and prints what it wrote. Safe to re-run:
it overwrites only files it owns.

Design rule: the generated pages share the header, footer and section styles
with the rest of the site, so a case study never looks like a different site.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "projects.js"
OUT = ROOT / "work"


def load_projects():
    text = SRC.read_text()
    start = text.index("window.PROJECTS")
    start = text.index("[", start)
    depth, i = 0, start
    while i < len(text):
        if text[i] == "[":
            depth += 1
        elif text[i] == "]":
            depth -= 1
            if depth == 0:
                break
        i += 1
    return json.loads(text[start : i + 1])


